// B-V color index -> realistic star tint (hot blue -> cool orange-red)
function bvToColor(bv){
  bv = Math.max(-0.4, Math.min(2.0, bv));
  let r,g,b;
  if (bv < 0)        { r=0.62+0.4*(bv+0.4); g=0.74+0.3*(bv+0.4); b=1; }
  else if (bv < 0.4) { r=0.78+0.55*bv;      g=0.85+0.3*bv;       b=1; }
  else if (bv < 1.1) { r=1; g=1-0.25*(bv-0.4); b=1-0.55*(bv-0.4); }
  else               { r=1; g=0.82-0.35*(bv-1.1); b=0.61-0.4*(bv-1.1); }
  const h=v=>("0"+Math.round(Math.max(0,Math.min(1,v))*255).toString(16)).slice(-2);
  return "#"+h(r)+h(g)+h(b);
}
